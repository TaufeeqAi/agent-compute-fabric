"""Python SDK of Agent Compute Fabric: sandboxes, executions, snapshots and operations.

``Fabric`` is the synchronous client and ``AsyncFabric`` the asynchronous one::

    from agentcompute import Fabric

    with Fabric() as fabric:                      # ACF_API_KEY and ACF_BASE_URL
        sandbox = fabric.sandboxes.create("python", cpu=1, memory="512MiB", disk="1GiB")
        result = sandbox.exec(["python", "-V"])
        print(result.exit_code, result.text())
        sandbox.destroy()

Every call that changes something is one operation on the platform, carried under one idempotency key.
The package follows the operation to its end, retries only what is safe to repeat, and says precisely
which of the possible outcomes happened: see :mod:`agentcompute.errors`.
"""

