"""A black-box driver for the host agent: how the integration and isolation suites talk to the system.

===================  ==============================================================================================
``client``           the reference client as a subprocess (``$ACF_LOCAL``): exit codes, streams, ``--json`` documents
``wire``             the wire protocol without the client: any bytes a test wants to send, and fast arrangement
``hosts``            the test host (``acf-host-fake``): start, stop, restart, and the files it keeps
``settings``         the bounds the suites assert on, read from the files the host itself loads
``views``            typed, read-only views over the documents the host answers with
``netlab``           an "outside world" for the network suites on a real host (a namespace, a device pair, servers)
``base``             the driver's failure type, the client's exit codes, waiting with a deadline
===================  ==============================================================================================

``tests/integration/test_driver_selftest.py`` proves all of it against the test host, so that a mistake in the
driver is found on a laptop and not on the first run on a KVM host.
"""

