@dataclass
class Invocation:
    """One run of the command line against a scripted host."""

    result: Result
    connection: ScriptedConnection
    #: The configuration the command line was turned into (``None`` if no client was ever built).
    config: ClientConfig | None

    @property
    def exit_code(self) -> int:
        return self.result.exit_code

    @property
    def stdout(self) -> str:
        return self.result.stdout

    @property
    def stderr(self) -> str:
        return self.result.stderr


@pytest.fixture
def invoke(
    scripted: Callable[..., ScriptedConnection], clock: FakeClock, monkeypatch: pytest.MonkeyPatch
) -> Callable[..., Invocation]:
    """``invoke([args...], *steps)``: run ``acf-local`` in-process against a scripted transport on a fake clock."""

    def run(
        args: list[str],
        *script: Step,
        default: Step | None = None,
        env: dict[str, str] | None = None,
        stdin: str | None = None,
    ) -> Invocation:
        connection = scripted(*script, default=default)
        configs: list[ClientConfig] = []

        def new_client(cfg: ClientConfig) -> HostClient:
            configs.append(cfg)
            return HostClient(cfg, connection=connection, sleep=clock.sleep, monotonic=clock.monotonic)

        monkeypatch.setattr("acf_cli.common.new_client", new_client)
        result = CliRunner().invoke(app, args, env=env, input=stdin, catch_exceptions=False)
        return Invocation(result, connection, configs[0] if configs else None)

    return run


