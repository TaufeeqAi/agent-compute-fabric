//! The published schemas (contract §10.1, §24.2, INV-036), generated from the types the host
//! actually parses and emits.
//!
//! Two machine-readable contracts live under `execution/contracts/`:
//!
//! * `host-api.json` — the host API: the request and response envelopes, every method with its
//!   class, the roles that may call it and the schema of its `params`, the failure classes with
//!   where each may appear and its retry advice, and the closed state vocabularies.
//! * `event-schema.json` — one telemetry event.
//!
//! The schemas of the files a host reads or writes (configuration, safety profile, enrolment table,
//! image and snapshot manifests) are written under `schemas/`.
//!
//! All of them are checked in, and regenerated by the build: a difference is a failure, so a client
//! can never drift from the host silently. **The contract governs the schema, not the reverse**: the
//! tables in `domain` are transcribed from the contract and tested against it; this module only
//! projects them.

use std::path::{Path, PathBuf};

use schemars::{JsonSchema, Schema, SchemaGenerator, generate::SchemaSettings, schema_for};
use serde_json::{Value, json};

use super::{
    AcknowledgeParams, ExecParams, FEATURES, ListParams, OperationSelector, PROTOCOL, QuarantineReleaseParams, RequestEnvelope,
    ResponseEnvelope, RunOutputParams, RunSelector, SandboxCreateParams, SandboxSelector, SandboxTarget, SetModeParams,
    SnapshotCreateParams, SnapshotDeleteParams, SnapshotRestoreParams,
};
use crate::{
    authority::{EnrolmentDoc, ProfileDoc},
    config::HostConfig,
    domain::{HostMode, LifecycleState, Method, OperationState, OperationType, Role},
    error::{FailureClass, Result},
    storage::{ImageManifest, snapshots::SnapshotManifest},
    telemetry::Event,
};

/// File names of the two contracts.
pub const HOST_API_FILE: &str = "host-api.json";
pub const EVENT_SCHEMA_FILE: &str = "event-schema.json";

/// The schema of a method's `params`; `None` for a method that takes none.
fn params_schema(generator: &mut SchemaGenerator, method: Method) -> Option<Schema> {
    Some(match method {
        Method::SandboxCreate => generator.subschema_for::<SandboxCreateParams>(),
        Method::SandboxStart | Method::SandboxStop | Method::SandboxDestroy => generator.subschema_for::<SandboxTarget>(),
        Method::ExecRun => generator.subschema_for::<ExecParams>(),
        Method::SnapshotCreate => generator.subschema_for::<SnapshotCreateParams>(),
        Method::SnapshotRestore => generator.subschema_for::<SnapshotRestoreParams>(),
        Method::SnapshotDelete => generator.subschema_for::<SnapshotDeleteParams>(),
        Method::OperationCancel | Method::OperationGet => generator.subschema_for::<OperationSelector>(),
        Method::SandboxInspect => generator.subschema_for::<SandboxSelector>(),
        Method::SandboxList | Method::SnapshotList | Method::OperationList => generator.subschema_for::<ListParams>(),
        Method::RunInspect => generator.subschema_for::<RunSelector>(),
        Method::RunOutput => generator.subschema_for::<RunOutputParams>(),
        Method::HostInfo | Method::HostMetrics | Method::ProfileReload => return None,
        Method::QuarantineRelease => generator.subschema_for::<QuarantineReleaseParams>(),
        Method::HostSetMode => generator.subschema_for::<SetModeParams>(),
        Method::HostAcknowledge => generator.subschema_for::<AcknowledgeParams>(),
    })
}

/// Whether `params` may be omitted for `method` (list methods default every field).
const fn params_optional(method: Method) -> bool {
    matches!(method, Method::SandboxList | Method::SnapshotList | Method::OperationList)
}

fn labels<T: serde::Serialize>(values: &[T]) -> Result<Vec<Value>> {
    values.iter().map(|v| Ok(serde_json::to_value(v)?)).collect()
}

/// The host API description. A JSON Schema document (draft 2020-12): validate a request with
/// `{"$ref": "#/$defs/RequestEnvelope"}`, a response with `{"$ref": "#/$defs/ResponseEnvelope"}`,
/// and the `params` of a method with the `params` reference of its entry in `methods`.
pub fn host_api() -> Result<Value> {
    let mut generator = SchemaSettings::draft2020_12().into_generator();
    let request = generator.subschema_for::<RequestEnvelope>().to_value();
    let response = generator.subschema_for::<ResponseEnvelope>().to_value();
    let roles = [Role::Observer, Role::Caller, Role::Operator];
    let mut methods = Vec::with_capacity(Method::ALL.len());
    for &m in Method::ALL {
        let params = params_schema(&mut generator, m).map(Schema::to_value);
        let allowed: Vec<Role> = roles.into_iter().filter(|r| m.allowed_for(*r)).collect();
        methods.push(json!({
            "name": m.name(),
            "class": m.class(),
            "roles": allowed,
            // Granting, containment and operator methods create a durable operation: they require
            // `operation_id` and `issued_at`, and answer `OPERATION` or `REFUSED`. Reads answer
            // `RESULT` or `REFUSED`.
            "creates_operation": m.requires_operation(),
            "answer": if m.requires_operation() { "OPERATION" } else { "RESULT" },
            "params": params,
            "params_required": params_schema(&mut generator, m).is_some() && !params_optional(m),
        }));
    }
    let failure_classes: Vec<Value> = FailureClass::ALL
        .iter()
        .map(|c| {
            json!({
                "class": c,
                "may_refuse": c.can_refuse(),
                "may_fail_operation": c.can_fail_operation(),
                "retry": c.retry_advice(),
            })
        })
        .collect();
    let defs = generator.take_definitions(true);
    Ok(json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "urn:acf:host-api:2",
        "title": "Agent Compute Fabric host API",
        "description": "Generated from the host agent's types. Do not edit: run `acf-host schema`.",
        "protocol": PROTOCOL,
        "features": FEATURES,
        "request": request,
        "response": response,
        "methods": methods,
        "failure_classes": failure_classes,
        "operation_types": labels(OperationType::ALL)?,
        "operation_states": labels(&OperationState::ALL)?,
        "lifecycle_states": labels(&LifecycleState::ALL)?,
        "host_modes": labels(&HostMode::ALL)?,
        "$defs": defs,
    }))
}

/// The schema of one telemetry event.
pub fn event_schema() -> Result<Value> {
    Ok(serde_json::to_value(schema_for!(Event))?)
}

fn pretty(v: &Value) -> Result<String> {
    let mut text = serde_json::to_string_pretty(v)?;
    text.push('\n');
    Ok(text)
}

fn write_value(dir: &Path, name: &str, v: &Value) -> Result<PathBuf> {
    let p = dir.join(name);
    std::fs::write(&p, pretty(v)?)?;
    Ok(p)
}

fn write<T: JsonSchema>(dir: &Path, name: &str) -> Result<PathBuf> {
    write_value(dir, name, &serde_json::to_value(schema_for!(T))?)
}

/// Write `host-api.json` and `event-schema.json` into `dir`.
pub fn write_contracts(dir: &Path) -> Result<Vec<PathBuf>> {
    std::fs::create_dir_all(dir)?;
    Ok(vec![write_value(dir, HOST_API_FILE, &host_api()?)?, write_value(dir, EVENT_SCHEMA_FILE, &event_schema()?)?])
}

/// Write the schemas of the host's file formats into `dir`.
pub fn write_all(dir: &Path) -> Result<Vec<PathBuf>> {
    std::fs::create_dir_all(dir)?;
    Ok(vec![
        write::<HostConfig>(dir, "host-config.schema.json")?,
        write::<ProfileDoc>(dir, "safety-profile.schema.json")?,
        write::<EnrolmentDoc>(dir, "enrolment.schema.json")?,
        write::<ImageManifest>(dir, "image-manifest.schema.json")?,
        write::<SnapshotManifest>(dir, "snapshot-manifest.schema.json")?,
    ])
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::domain::OperationClass;

    fn def<'a>(api: &'a Value, name: &str) -> &'a Value {
        api["$defs"].get(name).unwrap_or_else(|| panic!("no definition `{name}`"))
    }

    fn resolve<'a>(api: &'a Value, schema: &'a Value) -> &'a Value {
        match schema.get("$ref").and_then(Value::as_str) {
            Some(r) => def(api, r.strip_prefix("#/$defs/").unwrap_or_else(|| panic!("unexpected reference {r}"))),
            None => schema,
        }
    }

    #[test]
    fn the_api_description_lists_exactly_the_command_set_with_its_classes_and_roles() {
        let api = host_api().unwrap();
        assert_eq!(api["protocol"], PROTOCOL);
        let methods = api["methods"].as_array().unwrap();
        assert_eq!(methods.len(), Method::ALL.len());
        for (entry, &m) in methods.iter().zip(Method::ALL) {
            assert_eq!(entry["name"], m.name());
            assert_eq!(entry["class"], serde_json::to_value(m.class()).unwrap());
            assert_eq!(entry["creates_operation"], m.class() != OperationClass::Read, "{m}");
            let roles: Vec<&str> = entry["roles"].as_array().unwrap().iter().filter_map(Value::as_str).collect();
            assert!(roles.contains(&"operator"), "{m}: an operator may call every method");
            assert_eq!(roles.contains(&"caller"), m.class() != OperationClass::Operator, "{m}");
            assert_eq!(roles.contains(&"observer"), matches!(m, Method::HostInfo | Method::HostMetrics), "{m}");
        }
    }

    #[test]
    fn every_object_a_caller_can_send_refuses_unknown_fields() {
        // VR-2: a field that narrows what a sandbox may do must never be ignored silently.
        let api = host_api().unwrap();
        assert_eq!(def(&api, "RequestEnvelope")["additionalProperties"], json!(false));
        for entry in api["methods"].as_array().unwrap() {
            if entry["params"].is_null() {
                assert_eq!(entry["params_required"], false);
                continue;
            }
            let schema = resolve(&api, &entry["params"]);
            assert_eq!(schema["additionalProperties"], json!(false), "{}: params must be strict", entry["name"]);
        }
        // nested request objects, by name
        for name in ["SandboxResources", "CommandSpec", "RunLimitsRequest", "Cursor", "SecretRef", "AllowEntry"] {
            assert_eq!(def(&api, name)["additionalProperties"], json!(false), "{name}");
        }
    }

    #[test]
    fn the_failure_classes_carry_the_refusal_and_operation_columns_and_retry_advice() {
        let api = host_api().unwrap();
        let classes = api["failure_classes"].as_array().unwrap();
        assert_eq!(classes.len(), FailureClass::ALL.len());
        for (entry, class) in classes.iter().zip(FailureClass::ALL) {
            assert_eq!(entry["class"], serde_json::to_value(class).unwrap());
            assert_eq!(entry["may_refuse"], class.can_refuse());
            assert_eq!(entry["may_fail_operation"], class.can_fail_operation());
            assert!(entry["may_refuse"] == true || entry["may_fail_operation"] == true, "{class:?} can appear nowhere");
        }
        assert_eq!(api["operation_states"].as_array().unwrap().len(), 7);
        assert_eq!(api["host_modes"], json!(["STARTING", "SERVING", "DRAINING", "CONTAINMENT", "READ_ONLY"]));
    }

    #[test]
    fn run_results_mark_the_provenance_of_every_field() {
        // OB-9: a consumer can tell a host-observed fact from a guest-reported one from the schema.
        let api = host_api().unwrap();
        let props = def(&api, "RunResult")["properties"].as_object().unwrap();
        assert!(!props.is_empty());
        for (field, schema) in props {
            let p = schema.get("x-provenance").and_then(Value::as_str);
            assert!(matches!(p, Some("HOST_OBSERVED" | "GUEST_REPORTED")), "RunResult.{field} has no provenance marker");
        }
    }

    #[test]
    fn generation_is_deterministic_and_every_file_is_written() {
        assert_eq!(pretty(&host_api().unwrap()).unwrap(), pretty(&host_api().unwrap()).unwrap());
        let d = tempfile::tempdir().unwrap();
        let contracts = write_contracts(d.path()).unwrap();
        let formats = write_all(d.path()).unwrap();
        assert_eq!((contracts.len(), formats.len()), (2, 5));
        for f in contracts.iter().chain(&formats) {
            let v: Value = serde_json::from_slice(&std::fs::read(f).unwrap()).unwrap();
            assert!(v.get("$schema").is_some(), "{}", f.display());
        }
        let event: Value = serde_json::from_slice(&std::fs::read(d.path().join(EVENT_SCHEMA_FILE)).unwrap()).unwrap();
        for field in ["schema_version", "host_id", "lineage", "activation_epoch", "seq", "commit_seq", "timestamp", "kind"] {
            assert!(event["properties"].get(field).is_some(), "event field {field}");
        }
    }

    /// T-API-01 / INV-036: the checked-in contracts are exactly what these types generate.
    #[test]
    fn the_checked_in_contracts_match_the_types() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join("contracts");
        for (file, generated) in [(HOST_API_FILE, host_api().unwrap()), (EVENT_SCHEMA_FILE, event_schema().unwrap())] {
            let path = root.join(file);
            let on_disk = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}; run `make schema`", path.display()));
            assert_eq!(on_disk.replace("\r\n", "\n"), pretty(&generated).unwrap(), "{file} is stale; run `make schema`");
        }
    }
}
